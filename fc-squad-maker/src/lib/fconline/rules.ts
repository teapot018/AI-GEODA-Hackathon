/* ── 강화 팀컬러 (물결) ────────────────────────────────── */

/**
 * 스쿼드에 **일정 강화 단계 이상인 선수가 몇 명 있는가**로 발동하는
 * 팀컬러. 게임에서는 '물결' 이라고 부른다.
 *
 * ── 왜 이게 중요한가 ──
 * 이 프로젝트의 팀컬러는 그동안 **클럽·국가·리그 인원수만** 셌다.
 * 그런데 실제 FC 온라인에서 스쿼드를 짤 때 사람들이 먼저 말하는 것은
 * "은카 스쿼드", "8금 스쿼드" 다 — 즉 **강화 단계로 발동하는 팀컬러**이고,
 * 우리 화면에는 그 축이 통째로 없었다. 같은 카드 11장이라도 5강이냐
 * 8강이냐에 따라 전 선수 능력치가 달라지는데 우리는 0으로 봤다.
 *
 * ── 확인 수준 ──
 * 단계 이름과 강화 임계치(3/5/8/11강), 인원 조건(5명/8명)은 여러
 * 커뮤니티 정리에서 일관되게 나온다. 다만 **넥슨 공지 원문으로
 * 대조하지 못했다**(이 환경에서 넥슨 도메인이 막혀 있다). 특히 능력치
 * 보너스 수치는 자료마다 조금씩 다를 수 있어 UNVERIFIED 로 둔다.
 *
 * 그래서 이 표는 계층 B(공식 규칙)가 아니라 **미검증**으로 표기한다.
 * 화면에서도 그렇게 뜬다. 값을 안 쓰는 것보다는, 쓰되 확인 못 했다고
 * 적는 편이 실제 게임에 가깝다 — 없는 축을 0으로 두는 것도 틀린 값이다.
 */
