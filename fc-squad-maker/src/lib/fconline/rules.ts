/* ── 등록 가격대 (하한가 / 상한가) ────────────────────────── */

/**
 * FC 온라인 이적시장은 카드를 **아무 가격에나 걸 수 없다.**
 *
 * 기준가를 중심으로 게임이 정한 구간이 있고, 그 밖으로는 등록 자체가
 * 되지 않는다. 이 구간의 두 끝을 게임에서 **하한가 / 상한가** 라고 부른다.
 *
 * ── 왜 여기에 값이 없는가 ──
 * 배율을 확정하지 못했다. 커뮤니티 정리에는 기준가 ±10% 라는 설명과,
 * 강화 단계별로 하한가 배율이 따로 있고 그 최대치가 35%→30% 로 조정된
 * 적이 있다는 설명이 같이 나온다 — 두 설명이 가리키는 규칙이 같은 것인지
 * 확인하지 못했고, 넥슨 공지 원문은 이 환경에서 열 수 없다.
 *
 * 그래서 **계산하지 않는다.** 반쯤 아는 배율로 "하한가 980만" 을 찍으면,
 * 사용자는 그 값을 게임이 강제하는 선으로 읽고 그 아래는 시도조차 하지
 * 않는다. 틀린 하한가는 없는 하한가보다 나쁘다.
 *
 * ── 이 상수가 하는 일 ──
 * 이름을 **점유**한다. 우리 화면에는 관측 표본의 사분위값(p25/p75)이
 * 있는데, 그걸 '하한가/상한가' 라고 부르고 싶은 유혹이 늘 있다. 둘은
 * 전혀 다른 물건이다 — 하나는 게임이 강제하는 선(계층 B)이고 하나는
 * 우리가 본 거래의 분포(관측 표본)다. 이 주석이 그 구분을 붙들어 둔다.
 */
